#!/usr/bin/env python3
"""Write the current schema of each database to deploy/schema/.

A snapshot, not the source. The shape is created by the `SCHEMA` constant in
each store; this writes down what that produces, so a later version can be
diffed against it and a fork can see exactly what a version was.

Run it when `SCHEMA_VERSION` goes up, and commit the new file alongside the
migration script:

    python3 deploy/schema/dump.py

Older files are never rewritten -- v1 is what v1 was, even if it was wrong.
"""

from __future__ import annotations

import pathlib
import sqlite3
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT))


def dump(db: sqlite3.Connection, path: pathlib.Path, title: str, version: int) -> None:
    rows = db.execute(
        "SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'"
        " ORDER BY type DESC, name"
    ).fetchall()
    out = [
        f"-- {title}, schema v{version}.",
        "--",
        "-- A snapshot, not the source: the shape is created by the SCHEMA constant",
        "-- in the code. This file is here so a later version can be diffed against",
        "-- it, and so a fork can see exactly what a version was. Regenerated by",
        "-- deploy/schema/dump.py; see docs/schema.md.",
        "",
        f"PRAGMA user_version = {version};",
        "",
    ]
    for (sql,) in rows:
        out.append(sql.strip().rstrip(";") + ";")
        out.append("")
    path.write_text("\n".join(out))
    print(f"{path.relative_to(ROOT)}  {len(rows)} objects")


def main() -> int:
    from chickenbot.store import SCHEMA_VERSION, Store

    from external.github.store import SCHEMA_VERSION as GH_VERSION
    from external.github.store import Store as GhStore

    with tempfile.TemporaryDirectory() as tmp:
        where = pathlib.Path(tmp)
        st = Store(where / "a.db")
        dump(st._db, HERE / f"chickenbot-v{SCHEMA_VERSION}.sql", "chickenbot.db", SCHEMA_VERSION)
        st.close()
        gh = GhStore(where / "b.db")
        dump(gh.db, HERE / f"github-tool-v{GH_VERSION}.sql", "github-tool.db (the mirror; a cache)", GH_VERSION)
        gh.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
